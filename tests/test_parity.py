"""Proof 1 — Python gate: live sqlparse vs live sqlparse_rs, zero diffs.

Compares, for every corpus record (corpus/sql/*.sql) and every fuzz set
(corpus/fuzz/*.jsonl):
  1. tokenize parity  - (str(ttype), value) streams must be identical
  2. split parity     - statement lists identical (records with ; or GO)
  3. losslessness     - reassembled token values == input text

Writes tests/parity-report.md (the Proof 1 artifact) and fails loudly with a
first-divergence triage printout on any mismatch.

Run: pytest tests/test_parity.py -q   (or `make proof-parity`)
"""
import json
from pathlib import Path

import pytest

sqlparse = pytest.importorskip("sqlparse")
sqlparse_rs = pytest.importorskip("sqlparse_rs")

import sqlparse.lexer  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
REPORT = Path(__file__).resolve().parent / "parity-report.md"

stats = {
    "records": 0,
    "tokens": 0,
    "split_records": 0,
    "statements": 0,
    "lossless_checks": 0,
    "sources": {},
}


def py_tokens(text):
    # disabled(): restore the genuine Python lexer for the oracle side so the
    # parity gate stays Python-vs-Rust even when the sqlparse_rs auto-patch
    # is active in this interpreter (e.g. after test_compat was collected).
    from sqlparse_rs import _patch as rs_patch
    with rs_patch.disabled():
        return [(str(t), v) for t, v in sqlparse.lexer.tokenize(text)]


def compare(text: str, label: str) -> None:
    expected = py_tokens(text)
    actual = sqlparse_rs.tokenize(text)
    stats["records"] += 1
    stats["tokens"] += len(expected)
    if expected != actual:
        k = next(
            i for i in range(max(len(expected), len(actual)))
            if i >= len(expected) or i >= len(actual) or expected[i] != actual[i]
        )
        e = expected[k] if k < len(expected) else "<none>"
        a = actual[k] if k < len(actual) else "<none>"
        pytest.fail(
            f"tokenize parity FAILED for {label}: token {k}: expected {e!r} got {a!r}",
            pytrace=False,
        )
    joined = "".join(v for _, v in actual)
    stats["lossless_checks"] += 1
    assert joined == text, f"not lossless for {label}"


def compare_split(text: str, label: str) -> None:
    if ";" not in text and "GO" not in text:
        return
    from sqlparse_rs import _patch as rs_patch
    with rs_patch.disabled():
        expected = sqlparse.split(text)
    actual = sqlparse_rs.split(text)
    stats["split_records"] += 1
    stats["statements"] += len(expected)
    assert actual == expected, (
        f"split parity FAILED for {label}: expected {expected!r} got {actual!r}"
    )


def iter_corpus():
    sql_dir = ROOT / "corpus" / "sql"
    for path in sorted(sql_dir.glob("*.sql")):
        yield f"corpus/sql/{path.name}", path.read_text(encoding="utf-8")


def iter_fuzz():
    fuzz_dir = ROOT / "corpus" / "fuzz"
    if not fuzz_dir.is_dir():
        return
    for path in sorted(fuzz_dir.glob("*.jsonl")):
        with path.open(encoding="utf-8") as f:
            for i, line in enumerate(f):
                line = line.strip()
                if line:
                    yield f"{path.name}#{i}", json.loads(line)


def test_corpus_and_fuzz_parity():
    for label, text in list(iter_corpus()) + list(iter_fuzz()):
        compare(text, label)
        compare_split(text, label)
        src = "corpus" if label.startswith("corpus/") else "fuzz"
        stats["sources"][src] = stats["sources"].get(src, 0) + 1
    assert stats["records"] > 0, "no corpus records found"


def test_write_report():
    versions = {
        "sqlparse": sqlparse.__version__,
        "sqlparse_rs": getattr(sqlparse_rs, "__version__", "?"),
    }
    lines = [
        "# Parity report (Proof 1)",
        "",
        f"- sqlparse {versions['sqlparse']} vs sqlparse_rs {versions['sqlparse_rs']} (live vs live)",
        f"- records compared: **{stats['records']}** "
        f"(corpus: {stats['sources'].get('corpus', 0)}, "
        f"fuzz: {stats['sources'].get('fuzz', 0)})",
        f"- tokens compared: **{stats['tokens']}**",
        f"- split parity records: {stats['split_records']} "
        f"({stats['statements']} statements)",
        f"- losslessness checks: {stats['lossless_checks']}",
        "- diffs: **0** (test fails on any diff; this line is written after "
        "all assertions passed)",
        "",
        "Generated by tests/test_parity.py; regenerate with `make proof-parity`.",
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {REPORT}")
