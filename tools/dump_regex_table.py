#!/usr/bin/env python3
"""Dump the REAL sqlparse lexer tables -> PORT_MATRIX.md (ground truth).

Run with the exact sqlparse version you are porting:
  pip install sqlparse==0.6.0
  python3 tools/dump_regex_table.py > PORT_MATRIX.md

Everything downstream (scanner slices, keyword codegen, micro-cases) treats
this output as the spec. If introspection fails anywhere, the script prints
an explicit marker instead of guessing - in that case, read
sqlparse/lexer.py and sqlparse/keywords.py directly and adapt this script.
"""
import inspect
import re
import sys


def get_default_lexer():
    from sqlparse.lexer import Lexer

    try:
        return Lexer.get_default_instance()
    except AttributeError:
        lexer = Lexer()
        lexer.default_initialization()
        return lexer


def flag_names(rx) -> str:
    names = []
    if rx.flags & re.IGNORECASE:
        names.append("IGNORECASE")
    if rx.flags & re.UNICODE:
        names.append("UNICODE")
    if rx.flags & re.MULTILINE:
        names.append("MULTILINE")
    if rx.flags & re.DOTALL:
        names.append("DOTALL")
    return ",".join(names) if names else "(none)"


def main() -> None:
    try:
        import sqlparse
        from sqlparse import keywords as K
        from sqlparse.lexer import Lexer
    except ImportError:
        sys.exit("dump_regex_table: pip install sqlparse==0.6.0 first")

    out = []
    out.append("# PORT_MATRIX - generated by tools/dump_regex_table.py")
    out.append(f"# sqlparse version: {sqlparse.__version__}")
    out.append("# THIS FILE IS THE GROUND TRUTH for the Rust scanner port.")
    out.append("")

    # 1. Compiled per-position regex table, in order (FIRST MATCH WINS).
    out.append("## _SQL_REGEX - compiled, in order; FIRST match wins at every position\n")
    lexer = get_default_lexer()
    table = getattr(lexer, "_SQL_REGEX", None)
    if table is None:
        out.append("INTROSPECTION FAILED: no `_SQL_REGEX` attribute - read lexer.py "
                   "and fix this script.")
    else:
        for i, entry in enumerate(table):
            out.append(f"### rule {i}")
            try:
                match_fn, action = entry
                rx = match_fn.__self__  # the compiled re.Pattern behind .match
                action_s = str(action)
                if action_s.startswith("<object"):
                    action_s = "PROCESS_AS_KEYWORD"
                out.append(f"- pattern: {rx.pattern!r}")
                out.append(f"- flags  : {flag_names(rx)}")
                out.append(f"- action : {action_s}")
            except Exception as exc:
                out.append(f"- UNPACK FAILED: {entry!r} ({exc})")
    out.append("")

    # 2. Keyword dicts, in add order.
    out.append("## _keywords - add order; the FIRST dict containing a word wins\n")
    kw_lists = getattr(lexer, "_keywords", [])
    if not kw_lists:
        out.append("INTROSPECTION FAILED: no `_keywords` attribute.")
    for i, kwdict in enumerate(kw_lists):
        out.append(f"- dict {i}: {len(kwdict)} entries")
    out.append("")

    # 3. Delimited-span prepass regexes (dollar quotes + multiline comments).
    out.append("## keywords.py span-prepass regexes\n")
    for name in ("_DOLLAR_QUOTE_DELIM", "_DOLLAR_QUOTE_OPENER_OK",
                 "_COMMENT_HINT_OPEN", "_COMMENT_OPEN", "_COMMENT_CLOSE"):
        rx = getattr(K, name, None)
        if rx is not None:
            out.append(f"- {name} = {rx.pattern!r}  [flags: {flag_names(rx)}]")
        else:
            out.append(f"- {name} = (not found - read keywords.py directly)")
    out.append("")

    # 4. The exact loop being replaced - keep this next to the scanner code.
    out.append("## Lexer.get_tokens source - the loop you are replacing\n")
    try:
        out.append("```python")
        out.append(inspect.getsource(Lexer.get_tokens).rstrip())
        out.append("```")
    except Exception as exc:
        out.append(f"(source unavailable: {exc} - read sqlparse/lexer.py)")

    print("\n".join(out))


if __name__ == "__main__":
    main()
