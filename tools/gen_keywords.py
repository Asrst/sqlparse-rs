#!/usr/bin/env python3
"""Generate the Rust keyword table + manifest from the real sqlparse dicts.

Usage:
  python3 tools/gen_keywords.py [out_rs] [out_manifest]
  defaults:
    crates/sqlparse-core/src/keywords.rs
    corpus/keywords-manifest.txt

Priority semantics (mirrors Lexer.is_keyword): walk self._keywords in
add_keywords order - COMMON, ORACLE, MYSQL, PLPGSQL, HQL, MSACCESS,
SNOWFLAKE, BIGQUERY, KEYWORDS - and the FIRST dict containing the word
wins. Merged entries are then sorted by word so Rust can binary-search.
"""
import pathlib
import sys


def main() -> None:
    out_rs = pathlib.Path(sys.argv[1] if len(sys.argv) > 1
                          else "crates/sqlparse-core/src/keywords.rs")
    out_manifest = pathlib.Path(sys.argv[2] if len(sys.argv) > 2
                                else "corpus/keywords-manifest.txt")

    try:
        import sqlparse
        from sqlparse.lexer import Lexer
    except ImportError:
        sys.exit("gen_keywords: pip install sqlparse==0.6.0 first")

    try:
        lexer = Lexer.get_default_instance()
    except AttributeError:
        lexer = Lexer()
        lexer.default_initialization()

    kw_lists = getattr(lexer, "_keywords", None)
    if not kw_lists:
        sys.exit("gen_keywords: no _keywords attribute on the lexer; adapt this script")

    merged = {}
    for kwdict in kw_lists:
        for word, ttype in kwdict.items():
            merged.setdefault(word, str(ttype))  # first dict wins

    entries = sorted(merged.items())

    import json
    lines = [
        "// GENERATED by tools/gen_keywords.py - DO NOT EDIT BY HAND.",
        f"// source: sqlparse {sqlparse.__version__}; {len(entries)} entries;",
        "// priority: first dict in add_keywords order wins; sorted by word for",
        "// binary search. Token types are the exact str(ttype) strings the",
        "// oracle emits, so the differential test compares plain strings.",
        "pub static KEYWORD_ENTRIES: &[(&str, &str)] = &[",
    ]
    for word, ttype in entries:
        lines.append(f"    ({json.dumps(word)}, \"{ttype}\"),")
    lines += [
        "];",
        "",
        "pub fn lookup_keyword(word: &str) -> Option<&'static str> {",
        "    KEYWORD_ENTRIES",
        "        .binary_search_by(|(k, _)| (*k).cmp(word))",
        "        .ok()",
        "        .map(|i| KEYWORD_ENTRIES[i].1)",
        "}",
        "",
    ]
    out_rs.parent.mkdir(parents=True, exist_ok=True)
    out_rs.write_text("\n".join(lines), encoding="utf-8")

    man = [
        f"# keywords manifest - sqlparse {sqlparse.__version__}",
        f"# {len(entries)} unique words; priority = first dict in add order",
    ]
    man += [f"{word}\t{ttype}" for word, ttype in entries]
    out_manifest.parent.mkdir(parents=True, exist_ok=True)
    out_manifest.write_text("\n".join(man) + "\n", encoding="utf-8")

    print(f"gen_keywords: {len(entries)} entries -> {out_rs}, {out_manifest}")


if __name__ == "__main__":
    main()
