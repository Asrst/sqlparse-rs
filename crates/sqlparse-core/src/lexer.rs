/// (->>?|#>>?|@>|<@|\?\|?|\?&|-|#-) — alternatives in pattern order.
fn r_pg_ops(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    let c = ch[pos];
    let at = |i: usize, x: char| i < n && ch[i] == x;
    match c {
        '-' => {
            if at(pos + 1, '>') {
                if at(pos + 2, '>') {
                    Some(pos + 3)
                } else {
                    Some(pos + 2)
                }
            } else {
                Some(pos + 1) // lone '-' via the \- alternative
            }
        }
        '#' => {
            if at(pos + 1, '>') {
                if at(pos + 2, '>') {
                    Some(pos + 3)
                } else {
                    Some(pos + 2)
                }
            } else if at(pos + 1, '-') {
                Some(pos + 2)
            } else {
                None
            }
        }
        '@' if at(pos + 1, '>') => Some(pos + 2),
        '<' if at(pos + 1, '@') => Some(pos + 2),
        '?' => {
            if at(pos + 1, '|') || at(pos + 1, '&') {
                Some(pos + 2)
            } else {
                Some(pos + 1)
            }
        }
        _ => None,
    }
}
