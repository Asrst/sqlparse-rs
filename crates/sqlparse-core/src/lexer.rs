//! The Tier 1 scanner — a 1:1 behavioral port of python-sqlparse 0.6.0's
//! `Lexer.get_tokens` + `keywords.SQL_REGEX` (50 rules) + the
//! `find_delimited_spans` prepass.
//!
//! Semantics reproduced exactly:
//! * per position: span-opener precheck -> rules 0..49 IN ORDER, FIRST match
//!   wins (never longest match) -> single-char Error via the loop's for-else
//! * an unresolvable span opener (unclosed `$$` / `/*`) falls through to the
//!   rule table at that position
//! * regex backtracking behavior of the number/string/quoted-identifier
//!   rules is reproduced with explicit shrink loops / greedy+unwind scans
//!
//! `PORT_MATRIX.md` (generated by tools/dump_regex_table.py) is the spec.

use crate::keywords::lookup_keyword;
use crate::spans::{self, is_word_char};
use crate::ttype;

/// One token = (ttype name, zero-copy value slice of the input).
pub type Token<'a> = (&'static str, &'a str);

pub fn tokenize(input: &str) -> Vec<Token<'_>> {
    let chars: Vec<char> = input.chars().collect();
    // Byte offset of every char index (n+1 entries) for zero-copy slicing.
    let mut offs: Vec<usize> = Vec::with_capacity(chars.len() + 1);
    let mut o = 0usize;
    for c in &chars {
        offs.push(o);
        o += c.len_utf8();
    }
    offs.push(o);

    let spans = spans::find(&chars);
    let n = chars.len();
    let mut out: Vec<Token<'_>> = Vec::new();
    let mut pos = 0usize;

    while pos < n {
        // Delimited-span precheck (dollar quotes, multiline comments).
        if let Some((end, tt)) = spans.resolve(pos) {
            out.push((tt, &input[offs[pos]..offs[end]]));
            pos = end;
            continue;
        }

        // Rules 0..49 in exact SQL_REGEX order — first match wins.
        let m = rule_at(&chars, pos);
        match m {
            Some((tt, end)) => {
                out.push((tt, &input[offs[pos]..offs[end]]));
                pos = end;
            }
            None => {
                // for-else: single-char Error token.
                out.push((ttype::ERROR, &input[offs[pos]..offs[pos + 1]]));
                pos += 1;
            }
        }
    }
    out
}

type Match = Option<(&'static str, usize)>;

fn rule_at(ch: &[char], pos: usize) -> Match {
    let n = ch.len();

    // 0: (--|# )\+.*?(\r\n|\r|\n|$)  -> Comment.Single.Hint
    if let Some(end) = comment_line(ch, pos, true) {
        return Some((ttype::COMMENT_SINGLE_HINT, end));
    }
    // 1: (--|# ).*?(\r\n|\r|\n|$)    -> Comment.Single
    if let Some(end) = comment_line(ch, pos, false) {
        return Some((ttype::COMMENT_SINGLE, end));
    }
    // 2: (\r\n|\r|\n)                -> Newline
    if ch[pos] == '\n' {
        return Some((ttype::NEWLINE, pos + 1));
    }
    if ch[pos] == '\r' {
        let e = if pos + 1 < n && ch[pos + 1] == '\n' { pos + 2 } else { pos + 1 };
        return Some((ttype::NEWLINE, e));
    }
    // 3: \s+? (LAZY -> exactly one whitespace char per token)
    if is_py_ws(ch[pos]) {
        return Some((ttype::WHITESPACE, pos + 1));
    }
    // 4: :=   5: ::   6: \*
    if lit(ch, pos, ":=") {
        return Some((ttype::ASSIGNMENT, pos + 2));
    }
    if lit(ch, pos, "::") {
        return Some((ttype::PUNCTUATION, pos + 2));
    }
    if ch[pos] == '*' {
        return Some((ttype::WILDCARD, pos + 1));
    }
    // 7/8: `...` / ´...´ (with `` doubling) -> Name
    if let Some(end) = scan_quoted(ch, pos, '`', false) {
        return Some((ttype::NAME, end));
    }
    if let Some(end) = scan_quoted(ch, pos, '´', false) {
        return Some((ttype::NAME, end));
    }
    // 9: \? -> Placeholder
    if ch[pos] == '?' {
        return Some((ttype::NAME_PLACEHOLDER, pos + 1));
    }
    // 10: %(\(\w+\))?s -> Placeholder
    if let Some(end) = pct_placeholder(ch, pos) {
        return Some((ttype::NAME_PLACEHOLDER, end));
    }
    // 11: (?<!\w)[$:?]\w+ -> Placeholder
    if let Some(end) = sigil_placeholder(ch, pos) {
        return Some((ttype::NAME_PLACEHOLDER, end));
    }
    // 12: \\\w+ -> Generic.Command (psql)
    if ch[pos] == '\\' {
        let mut k = pos + 1;
        while k < n && is_word_char(ch[k]) {
            k += 1;
        }
        if k > pos + 1 {
            return Some((ttype::GENERIC_COMMAND, k));
        }
    }
    // 13: (CASE|IN|VALUES|USING|FROM|AS)\b -> Keyword
    if let Some(end) = word_set_b(ch, pos, &["CASE", "IN", "VALUES", "USING", "FROM", "AS"]) {
        return Some((ttype::KEYWORD, end));
    }
    // 14: (@|##|#)[A-ZÀ-Ü]\w+ -> Name
    if let Some(end) = at_name(ch, pos) {
        return Some((ttype::NAME, end));
    }
    // 15: [A-ZÀ-Ü]\w*(?=\s*\.(?!\d)) -> Name
    if let Some(end) = name_dot(ch, pos) {
        return Some((ttype::NAME, end));
    }
    // 16: (?<=\.)[A-ZÀ-Ü]\w* -> Name  (lookbehind IS live with re.match+pos)
    if pos > 0 && ch[pos - 1] == '.' && is_letter_class(ch[pos]) {
        let mut k = pos + 1;
        while k < n && is_word_char(ch[k]) {
            k += 1;
        }
        return Some((ttype::NAME, k));
    }
    // 17: [A-ZÀ-Ü]\w*(?=\() -> Name
    if is_letter_class(ch[pos]) {
        let mut k = pos + 1;
        while k < n && is_word_char(ch[k]) {
            k += 1;
        }
        if k < n && ch[k] == '(' {
            return Some((ttype::NAME, k));
        }
    }
    // 18: -?0x[\dA-F]+ -> Number.Hexadecimal
    if let Some(end) = r_hex(ch, pos) {
        return Some((ttype::NUMBER_HEX, end));
    }
    // 19: -?\d+(\.\d+)?E-?\d+ -> Number.Float
    if let Some(end) = r_sci(ch, pos) {
        return Some((ttype::NUMBER_FLOAT, end));
    }
    // 20: (?![_A-ZÀ-Ü])-?(\d+(\.\d*)|\.\d+)(?![_A-ZÀ-Ü]) -> Number.Float
    if let Some(end) = r_float(ch, pos) {
        return Some((ttype::NUMBER_FLOAT, end));
    }
    // 21: (?![_A-ZÀ-Ü])-?\d+(?![_A-ZÀ-Ü]) -> Number.Integer
    if let Some(end) = r_int(ch, pos) {
        return Some((ttype::NUMBER_INTEGER, end));
    }
    // 22/23: '...' / "..." (with doubling + \-escape) -> String.Single/Symbol
    if let Some(end) = scan_quoted(ch, pos, '\'', true) {
        return Some((ttype::STRING_SINGLE, end));
    }
    if let Some(end) = scan_quoted(ch, pos, '"', true) {
        return Some((ttype::STRING_SYMBOL, end));
    }
    // 24: (""|".*?[^\\]") -> String.Symbol (fires only if 23 failed)
    if let Some(end) = symbol_late(ch, pos) {
        return Some((ttype::STRING_SYMBOL, end));
    }
    // 25: (?<![\w\])])(\[[^\]\[]+\]) -> Name
    if let Some(end) = bracket_name(ch, pos) {
        return Some((ttype::NAME, end));
    }
    // 26: JOIN variants -> Keyword
    if let Some(end) = r_join(ch, pos) {
        return Some((ttype::KEYWORD, end));
    }
    // 27: END(\s+(IF|LOOP|WHILE|FOR|CASE))?\b -> Keyword
    if let Some(end) = r_end(ch, pos) {
        return Some((ttype::KEYWORD, end));
    }
    // 28: IF\s+(NOT\s+)?EXISTS\b -> Keyword
    if let Some(end) = r_if_exists(ch, pos) {
        return Some((ttype::KEYWORD, end));
    }
    // 29: NOT\s+NULL\b -> Keyword
    if let Some(end) = phrase_b(ch, pos, &["NOT"], &["NULL"]) {
        return Some((ttype::KEYWORD, end));
    }
    // 30: (ASC|DESC)(\s+NULLS\s+(FIRST|LAST))?\b -> Keyword.Order
    if let Some(end) = r_order_nulls(ch, pos) {
        return Some((ttype::KEYWORD_ORDER, end));
    }
    // 31: (ASC|DESC)\b -> Keyword.Order
    if let Some(end) = word_set_b(ch, pos, &["ASC", "DESC"]) {
        return Some((ttype::KEYWORD_ORDER, end));
    }
    // 32: NULLS\s+(FIRST|LAST)\b -> Keyword.Order
    if let Some(end) = phrase_b(ch, pos, &["NULLS"], &["FIRST", "LAST"]) {
        return Some((ttype::KEYWORD_ORDER, end));
    }
    // 33: UNION\s+ALL\b -> Keyword
    if let Some(end) = phrase_b(ch, pos, &["UNION"], &["ALL"]) {
        return Some((ttype::KEYWORD, end));
    }
    // 34: CREATE(\s+OR\s+REPLACE)?\b -> Keyword.DDL
    if let Some(end) = r_create(ch, pos) {
        return Some((ttype::KEYWORD_DDL, end));
    }
    // 35: DOUBLE\s+PRECISION\b -> Name.Builtin
    if let Some(end) = phrase_b(ch, pos, &["DOUBLE"], &["PRECISION"]) {
        return Some((ttype::NAME_BUILTIN, end));
    }
    // 36-39: GROUP BY / ORDER BY / PRIMARY KEY / HANDLER FOR -> Keyword
    if let Some(end) = phrase_b(ch, pos, &["GROUP"], &["BY"]) {
        return Some((ttype::KEYWORD, end));
    }
    if let Some(end) = phrase_b(ch, pos, &["ORDER"], &["BY"]) {
        return Some((ttype::KEYWORD, end));
    }
    if let Some(end) = phrase_b(ch, pos, &["PRIMARY"], &["KEY"]) {
        return Some((ttype::KEYWORD, end));
    }
    if let Some(end) = phrase_b(ch, pos, &["HANDLER"], &["FOR"]) {
        return Some((ttype::KEYWORD, end));
    }
    // 40: GO(\s\d+)\b -> Keyword
    if let Some(end) = r_go(ch, pos) {
        return Some((ttype::KEYWORD, end));
    }
    // 41: (LATERAL\s+VIEW\s+)(EXPLODE|INLINE|PARSE_URL_TUPLE|POSEXPLODE|STACK)\b
    if let Some(end) = r_lateral_view(ch, pos) {
        return Some((ttype::KEYWORD, end));
    }
    // 42: (AT|WITH')\s+TIME\s+ZONE\s+'[^']+' -> Keyword.TZCast
    if let Some(end) = r_tzcast(ch, pos) {
        return Some((ttype::KEYWORD_TZCAST, end));
    }
    // 43: (NOT\s+)?(LIKE|ILIKE|RLIKE)\b -> Operator.Comparison
    if let Some(end) = r_not_like(ch, pos) {
        return Some((ttype::OPERATOR_COMPARISON, end));
    }
    // 44: (NOT\s+)?(REGEXP)(\s+(BINARY))?\b -> Operator.Comparison
    if let Some(end) = r_regexp(ch, pos) {
        return Some((ttype::OPERATOR_COMPARISON, end));
    }
    // 45: \w[$#\w]* -> PROCESS_AS_KEYWORD (dict lookup) or Name
    if is_word_char(ch[pos]) {
        let mut k = pos + 1;
        while k < n && (is_word_char(ch[k]) || ch[k] == '$' || ch[k] == '#') {
            k += 1;
        }
        let word: String = ch[pos..k].iter().collect();
        let upper = word.to_uppercase(); // Python str.upper()
        let tt = lookup_keyword(&upper).unwrap_or(ttype::NAME);
        return Some((tt, k));
    }
    // 46: [;:()\[\],.] -> Punctuation
    if matches!(ch[pos], ';' | ':' | '(' | ')' | '[' | ']' | ',' | '.') {
        return Some((ttype::PUNCTUATION, pos + 1));
    }
    // 47: (->>?|#>>?|@>|<@|\?\|?|\?&|-|#-) -> Operator
    if let Some(end) = r_pg_ops(ch, pos) {
        return Some((ttype::OPERATOR, end));
    }
    // 48: [<>=~!]+ -> Operator.Comparison
    if matches!(ch[pos], '<' | '>' | '=' | '~' | '!') {
        let mut k = pos + 1;
        while k < n && matches!(ch[k], '<' | '>' | '=' | '~' | '!') {
            k += 1;
        }
        return Some((ttype::OPERATOR_COMPARISON, k));
    }
    // 49: [+/@#%^&|^-]+ -> Operator
    if matches!(ch[pos], '+' | '/' | '@' | '#' | '%' | '^' | '&' | '|' | '-') {
        let mut k = pos + 1;
        while k < n && matches!(ch[k], '+' | '/' | '@' | '#' | '%' | '^' | '&' | '|' | '-') {
            k += 1;
        }
        return Some((ttype::OPERATOR, k));
    }
    None
}

// ---------- rule helpers ----------

fn comment_line(ch: &[char], pos: usize, hint: bool) -> Option<usize> {
    let n = ch.len();
    let starts: [(&[char], usize); 2] = if hint {
        [(&['-', '-', '+'][..], 3), (&['#', ' ', '+'][..], 3)]
    } else {
        [(&['-', '-'][..], 2), (&['#', ' '][..], 2)]
    };
    for (pat, plen) in starts {
        if pos + plen <= n && ch[pos..pos + plen] == *pat {
            // lazy .*? up to the terminator — WHICH THE MATCH CONSUMES
            // (m.group() includes the trailing \r\n / \r / \n)
            let mut j = pos + plen;
            while j < n {
                if ch[j] == '\r' {
                    let e = if j + 1 < n && ch[j + 1] == '\n' { j + 2 } else { j + 1 };
                    return Some(e);
                }
                if ch[j] == '\n' {
                    return Some(j + 1);
                }
                j += 1;
            }
            return Some(n); // $ alternative: comment to EOF
        }
    }
    None
}

fn lit(ch: &[char], pos: usize, pat: &str) -> bool {
    let p: Vec<char> = pat.chars().collect();
    pos + p.len() <= ch.len() && ch[pos..pos + p.len()] == p[..]
}

/// Greedy + unwind scan for quoted literals:
///   open `quote`, then repeatedly: doubled quote | (optional) `\`quote |
///   any other char, finally a closing `quote`. EOF -> unwind the most
///   recent pair-consumption and reinterpret it (regex backtracking).
fn scan_quoted(ch: &[char], pos: usize, quote: char, allow_escape: bool) -> Option<usize> {
    let n = ch.len();
    if ch[pos] != quote {
        return None;
    }
    let mut i = pos + 1;
    let mut stack: Vec<usize> = Vec::new();
    loop {
        if i >= n {
            match stack.pop() {
                Some(p) => {
                    if ch[p] == quote {
                        return Some(p + 1); // close at the former pair start
                    }
                    i = p + 1; // escape point: '\' re-consumed as ordinary char
                    continue;
                }
                None => return None,
            }
        }
        let c = ch[i];
        if c == quote {
            if i + 1 < n && ch[i + 1] == quote {
                stack.push(i);
                i += 2;
            } else {
                return Some(i + 1); // closing quote
            }
        } else if allow_escape && c == '\\' && i + 1 < n && ch[i + 1] == quote {
            stack.push(i);
            i += 2;
        } else {
            i += 1;
        }
    }
}

fn pct_placeholder(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if ch[pos] != '%' {
        return None;
    }
    let j = pos + 1;
    if j < n && ch[j] == '(' {
        // greedy group first: (\(\w+\))s
        let mut k = j + 1;
        while k < n && is_word_char(ch[k]) {
            k += 1;
        }
        if k > j + 1 && k < n && ch[k] == ')' && k + 1 < n && ch[k + 1] == 's' {
            return Some(k + 2);
        }
        return None; // group present but unusable; absent group needs 's' at '('
    }
    if j < n && ch[j] == 's' {
        return Some(j + 1);
    }
    None
}

fn sigil_placeholder(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if pos > 0 && is_word_char(ch[pos - 1]) {
        return None; // (?<!\w)
    }
    if !matches!(ch[pos], '$' | ':' | '?') {
        return None;
    }
    let mut k = pos + 1;
    while k < n && is_word_char(ch[k]) {
        k += 1;
    }
    if k > pos + 1 {
        Some(k)
    } else {
        None
    }
}

/// case-insensitive literal word match (patterns are ASCII); returns end.
fn ci_word(ch: &[char], pos: usize, word: &str) -> Option<usize> {
    let w: Vec<char> = word.chars().collect();
    if pos + w.len() > ch.len() {
        return None;
    }
    for (i, wc) in w.iter().enumerate() {
        if ch[pos + i].to_ascii_uppercase() != *wc {
            return None;
        }
    }
    Some(pos + w.len())
}

fn is_py_ws(c: char) -> bool {
    matches!(c, ' ' | '\t' | '\r' | '\n' | '\x0b' | '\x0c') || (!c.is_ascii() && c.is_whitespace())
}

fn ws_run(ch: &[char], pos: usize) -> usize {
    let mut k = pos;
    while k < ch.len() && is_py_ws(ch[k]) {
        k += 1;
    }
    k
}

/// \b word boundary after `end`.
fn boundary(ch: &[char], end: usize) -> bool {
    end >= ch.len() || !is_word_char(ch[end])
}

/// word-set + trailing \b (rules 13/31).
fn word_set_b(ch: &[char], pos: usize, words: &[&str]) -> Option<usize> {
    for w in words {
        if let Some(end) = ci_word(ch, pos, w) {
            if boundary(ch, end) {
                return Some(end);
            }
        }
    }
    None
}

/// word + \s+ (>=1 whitespace) — end after the whitespace run.
fn ci_word_ws(ch: &[char], pos: usize, word: &str) -> Option<usize> {
    let end = ci_word(ch, pos, word)?;
    let wend = ws_run(ch, end);
    if wend > end {
        Some(wend)
    } else {
        None
    }
}

/// (NOT \s+)? prefix helper; returns (new pos, matched?).
fn opt_not_ws(ch: &[char], pos: usize) -> (usize, bool) {
    if let Some(end) = ci_word(ch, pos, "NOT") {
        let wend = ws_run(ch, end);
        if wend > end {
            return (wend, true);
        }
    }
    (pos, false)
}

fn phrase_b(ch: &[char], pos: usize, a: &[&str], b: &[&str]) -> Option<usize> {
    let e1 = a.iter().find_map(|w| ci_word(ch, pos, w))?;
    let w1 = ws_run(ch, e1);
    if w1 == e1 {
        return None; // \s+ required
    }
    let e2 = b.iter().find_map(|w| ci_word(ch, w1, w))?;
    if boundary(ch, e2) {
        Some(e2)
    } else {
        None
    }
}

fn at_name(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    for sigil in ["@", "##", "#"] {
        if lit(ch, pos, sigil) {
            let j = pos + sigil.len();
            if j < n && is_letter_class(ch[j]) {
                let mut k = j + 1;
                while k < n && is_word_char(ch[k]) {
                    k += 1;
                }
                if k > j + 1 {
                    return Some(k);
                }
            }
        }
    }
    None
}

/// [A-ZÀ-Ü]\w*(?=\s*\.(?!\d)) — greedy \w* with shrink, \s* greedy with shrink.
fn name_dot(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if !is_letter_class(ch[pos]) {
        return None;
    }
    let wmax = {
        let mut k = pos + 1;
        while k < n && is_word_char(ch[k]) {
            k += 1;
        }
        k
    };
    for e in ((pos + 1)..=wmax).rev() {
        let wsmax = ws_run(ch, e);
        for w in (0..=(wsmax - e)).rev() {
            let t = e + w;
            if t < n && ch[t] == '.' {
                let after = t + 1;
                if after >= n || !ch[after].is_numeric() {
                    return Some(e);
                }
            }
        }
    }
    None
}

fn is_letter_class(c: char) -> bool {
    // [A-ZÀ-Ü] with IGNORECASE
    c.is_ascii_alphabetic() || ('À'..='Ü').contains(&c) || ('à'..='ü').contains(&c)
}

// ---------- numbers ----------

fn digits_run(ch: &[char], pos: usize) -> usize {
    let mut k = pos;
    while k < ch.len() && ch[k].is_numeric() {
        k += 1;
    }
    k
}

fn hex_run(ch: &[char], pos: usize) -> usize {
    let mut k = pos;
    while k < ch.len() && (ch[k].is_ascii_hexdigit() || (!ch[k].is_ascii() && ch[k].is_numeric())) {
        k += 1;
    }
    k
}

/// guard class [_A-ZÀ-Ü] with IGNORECASE.
fn guard_class(c: char) -> bool {
    c == '_' || is_letter_class(c)
}

fn guard_ok(ch: &[char], end: usize) -> bool {
    end >= ch.len() || !guard_class(ch[end])
}

fn r_hex(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    let starts: Vec<usize> = if ch[pos] == '-' {
        vec![pos + 1, pos]
    } else {
        vec![pos]
    };
    for p in starts {
        if p + 2 < n && ch[p] == '0' && (ch[p + 1] == 'x' || ch[p + 1] == 'X') {
            let e = hex_run(ch, p + 2);
            if e > p + 2 {
                return Some(e);
            }
        }
    }
    None
}

/// -?\d+(\.\d+)?E-?\d+  (exponent REQUIRED; backtracking: rightmost first)
fn r_sci(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    let starts: Vec<usize> = if ch[pos] == '-' {
        vec![pos + 1, pos]
    } else {
        vec![pos]
    };
    for p in starts {
        let lead_max = digits_run(ch, p) - p; // count, not end index
        for lead in (1..=lead_max).rev() {
            let q = p + lead;
            // (\.\d+)? — present needs >=1 digit
            let frac_max = if q < n && ch[q] == '.' {
                digits_run(ch, q + 1) - (q + 1)
            } else {
                0
            };
            for f in (0..=frac_max).rev() {
                let q2 = if f == 0 { q } else { q + 1 + f };
                if q2 >= n || !(ch[q2] == 'E' || ch[q2] == 'e') {
                    continue;
                }
                let r = q2 + 1;
                // -?
                let exp_starts: Vec<usize> = if r < n && ch[r] == '-' {
                    vec![r + 1, r]
                } else {
                    vec![r]
                };
                for rr in exp_starts {
                    let e = digits_run(ch, rr);
                    if e > rr {
                        return Some(e);
                    }
                }
            }
        }
    }
    None
}

/// (?![_A-ZÀ-Ü])-?(\d+(\.\d*)|\.\d+)(?![_A-ZÀ-Ü])
fn r_float(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if guard_class(ch[pos]) {
        return None;
    }
    let starts: Vec<usize> = if ch[pos] == '-' {
        vec![pos + 1, pos]
    } else {
        vec![pos]
    };
    for p in starts {
        // alt1: \d+ (\.\d*) — dot REQUIRED, digits after dot optional
        let lead_max = digits_run(ch, p) - p; // count, not end index
        for lead in (1..=lead_max).rev() {
            let q = p + lead;
            if q < n && ch[q] == '.' {
                let fmax = digits_run(ch, q + 1) - (q + 1);
                for f in (0..=fmax).rev() {
                    let end = q + 1 + f;
                    if guard_ok(ch, end) {
                        return Some(end);
                    }
                }
            }
        }
        // alt2: \.\d+
        if p < n && ch[p] == '.' {
            let fmax = digits_run(ch, p + 1) - (p + 1);
            for f in (1..=fmax).rev() {
                let end = p + 1 + f;
                if guard_ok(ch, end) {
                    return Some(end);
                }
            }
        }
    }
    None
}

/// (?![_A-ZÀ-Ü])-?\d+(?![_A-ZÀ-Ü])
fn r_int(ch: &[char], pos: usize) -> Option<usize> {
    if guard_class(ch[pos]) {
        return None;
    }
    let starts: Vec<usize> = if ch[pos] == '-' {
        vec![pos + 1, pos]
    } else {
        vec![pos]
    };
    for p in starts {
        let lead_max = digits_run(ch, p) - p; // count, not end index
        for lead in (1..=lead_max).rev() {
            let end = p + lead;
            if guard_ok(ch, end) {
                return Some(end);
            }
        }
    }
    None
}

/// (""|".*?[^\\]") — only reached when rule 23 failed.
fn symbol_late(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if ch[pos] != '"' {
        return None;
    }
    if pos + 1 < n && ch[pos + 1] == '"' {
        return Some(pos + 2);
    }
    // lazy .*? (no newline) then [^\\] then '"'
    let mut j = pos + 2;
    while j < n && ch[j] != '\n' {
        if ch[j] == '"' && ch[j - 1] != '\\' {
            return Some(j + 1);
        }
        j += 1;
    }
    None
}

/// (?<![\w\])])(\[[^\]\[]+\])
fn bracket_name(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    if pos > 0 && (is_word_char(ch[pos - 1]) || ch[pos - 1] == ']' || ch[pos - 1] == ')') {
        return None;
    }
    if ch[pos] != '[' {
        return None;
    }
    let mut k = pos + 1;
    while k < n && ch[k] != '[' && ch[k] != ']' {
        k += 1;
    }
    if k > pos + 1 && k < n && ch[k] == ']' {
        Some(k + 1)
    } else {
        None
    }
}

/// ((LEFT|RIGHT|FULL)\s+(INNER|OUTER|STRAIGHT)\s+|...)?JOIN\b — 5 attempts
/// in the regex's own backtracking order.
fn r_join(ch: &[char], pos: usize) -> Option<usize> {
    let lrf = ["LEFT", "RIGHT", "FULL"];
    let ios = ["INNER", "OUTER", "STRAIGHT"];
    let cn = ["CROSS", "NATURAL"];
    let attempts: [(&[&str], &[&str]); 5] = [
        (lrf.as_slice(), ios.as_slice()),
        (lrf.as_slice(), &[]),
        (&[], ios.as_slice()),
        (cn.as_slice(), &[]),
        (&[], &[]),
    ];
    for (p1, p2) in attempts {
        let mut j = pos;
        let mut ok = true;
        for grp in [p1, p2] {
            if !grp.is_empty() {
                match grp.iter().find_map(|w| ci_word_ws(ch, j, w)) {
                    Some(e) => j = e,
                    None => {
                        ok = false;
                        break;
                    }
                }
            }
        }
        if !ok {
            continue;
        }
        if let Some(e) = ci_word(ch, j, "JOIN") {
            if boundary(ch, e) {
                return Some(e);
            }
        }
    }
    None
}

