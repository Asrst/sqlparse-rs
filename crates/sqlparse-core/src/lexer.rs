/// (AT|WITH')\s+TIME\s+ZONE\s+'[^']+' — note the quote inside `WITH'`.
fn r_tzcast(ch: &[char], pos: usize) -> Option<usize> {
    let n = ch.len();
    let starts: Vec<usize> = vec![ci_word(ch, pos, "AT"), ci_word(ch, pos, "WITH'")]
        .into_iter()
        .flatten()
        .collect();
    for p in starts {
        let mut j = p;
        for step in ["TIME", "ZONE"] {
            let w = ws_run(ch, j);
            if w == j {
                break;
            }
            match ci_word(ch, w, step) {
                Some(e) => j = e,
                None => break,
            }
            // peek: keep going; validate fully below
            if j == p {
                break;
            }
        }
        // full shape check from p: ws TIME ws ZONE ws ' ... '
        let w1 = ws_run(ch, p);
        if w1 == p {
            continue;
        }
        let e1 = match ci_word(ch, w1, "TIME") {
            Some(e) => e,
            None => continue,
        };
        let w2 = ws_run(ch, e1);
        if w2 == e1 {
            continue;
        }
        let e2 = match ci_word(ch, w2, "ZONE") {
            Some(e) => e,
            None => continue,
        };
        let w3 = ws_run(ch, e2);
        if w3 == e2 || w3 >= n || ch[w3] != '\'' {
            continue;
        }
        let mut k = w3 + 1;
        while k < n && ch[k] != '\'' {
            k += 1;
        }
        if k > w3 + 1 && k < n {
            return Some(k + 1);
        }
    }
    None
}

